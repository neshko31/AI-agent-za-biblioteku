"""
Milvus collection schema for reviews.
"""

from pymilvus import DataType, Function, FunctionType, MilvusClient

from config import BM25_ANALYZER_LANGUAGE, REVIEWS_EMBEDDING_DIM, REVIEWS_NLIST

REVIEWS_OUTPUT_FIELDS = [
    "id",
    "user_id",
    "book_id",
    "review_id",
    "rating",
    "review_text",
    "date_created",
    "date_updated",
    "finished_at",
    "started_at",
    "n_comments",
    "n_likes"
]


def reviews_schema(client: MilvusClient):
    """
    Full schema for the reviews collection.
    Fields found in this collection:

    Scalar fields               - Metadata used for filtering, display, and faceting.
    review_embedding            - Embedding of the review's text.
    review_embedding_sparse     - Sparse embedding of the review's text.
    """
    schema = client.create_schema(
        auto_id=True,
        enable_dynamic_fields=False,
        description=(
            "Reviews collection with hybrid retrieval support. "
            "Uses the following vectors: "
            " - Dense vectors for review_text"
            " - Sparse vectors for review_text"
            "Supports multiple different searches."
        ),
    )

    # Scalar metadata
    schema.add_field("id", DataType.INT64, is_primary=True, description="Primary key for reviews, automatically generated by Milvus")
    schema.add_field("user_id", DataType.VARCHAR, max_length=32, description="Anonymous user ID from the GoodReads dataset")
    schema.add_field("book_id", DataType.VARCHAR, max_length=32, description="Book's stripped numerical ID from the GoodReads dataset")
    schema.add_field("review_id", DataType.VARCHAR, max_length=32, description="Review's ID from the GoodReads dataset")
    schema.add_field("rating", DataType.INT8, description="Review's rating for the book from the GoodReads dataset")
    schema.add_field("date_created", DataType.INT64, description="Review's date of creation from the GoodReads dataset")
    schema.add_field("date_updated", DataType.INT64, description="Review's date of updating from the GoodReads dataset")
    schema.add_field("started_at", DataType.INT64, description="Review's date of starting the book reading from the GoodReads dataset")
    schema.add_field("finished_at", DataType.INT64, description="Review's date of finishing the book reading from the GoodReads dataset")
    schema.add_field("n_comments", DataType.INT32, description="Review's number of comments, fixed to 0 during ingestion")
    schema.add_field("n_likes", DataType.INT32, description="Review's number of likes from the GoodReads dataset")

    # --- Text Field with Full-Text Search (Analyzer) Enabled ---
    schema.add_field(
        "review_text",
        DataType.VARCHAR,
        max_length=8192,
        enable_analyzer=True,
        analyzer_params={"type": BM25_ANALYZER_LANGUAGE},
        enable_match=True,
        description="Review's text from the GoodReads dataset"
    )

    # --- Vector fields ---
    # Dense vector
    schema.add_field("review_embedding", DataType.FLOAT_VECTOR, dim=REVIEWS_EMBEDDING_DIM, description="Dense text encoding from review's text")

    # Sparse vector (BM25)
    schema.add_field("review_embedding_sparse", DataType.SPARSE_FLOAT_VECTOR, is_function_output=True, description="Sparse text encoding from review's text")

    # BM25 sparse vector auto-population, it automatically converts review_text into sparse vectors during ingestion
    schema.add_function(Function(name="bm25_reviews", function_type=FunctionType.BM25, input_field_names=["review_text"], output_field_names=["review_embedding_sparse"]))

    return schema


def reviews_index_params(client: MilvusClient):
    """
    Index parameters for the reviews collection.

    Scalar indexes        — INVERTED for efficient WHERE filtering.
    Dense vector indexes  — IVF_FLAT with COSINE; one index per vector field.
    Sparse vector indexes — SPARSE_INVERTED_INDEX with BM25; one index per vector field.
    """
    idx = client.prepare_index_params()

    # Scalar indexes
    idx.add_index("user_id", index_type="INVERTED")
    idx.add_index("review_id", index_type="INVERTED")
    idx.add_index("book_id", index_type="INVERTED")
    idx.add_index("rating", index_type="INVERTED")
    idx.add_index("date_created", index_type="INVERTED")
    idx.add_index("date_updated", index_type="INVERTED")
    idx.add_index("finished_at", index_type="INVERTED")
    idx.add_index("started_at", index_type="INVERTED")
    idx.add_index("n_comments", index_type="INVERTED")
    idx.add_index("n_likes", index_type="INVERTED")

    # --- Dense vector index (required) ---
    # review_embedding
    idx.add_index(
        "review_embedding",
        index_type="IVF_FLAT",
        index_name="review_embedding_index",
        metric_type="COSINE",
        params={"nlist": REVIEWS_NLIST},
    )

    # --- Sparse vector index for traditional keyword/BM25 retrieval (required) ---
    # review_embedding_sparse
    idx.add_index(
        "review_embedding_sparse",
        index_type="SPARSE_INVERTED_INDEX",
        index_name="review_embedding_sparse_index",
        metric_type="BM25",
    )

    return idx