"""
Milvus collection schema for books collection.
"""

from pymilvus import DataType, Function, FunctionType, MilvusClient

from config import BM25_ANALYZER_LANGUAGE, BOOKS_COVER_EMBEDDING_DIM, BOOKS_DESCRIPTION_EMBEDDING_DIM, BOOKS_SUMMARY_EMBEDDING_DIM, BOOKS_NLIST

BOOKS_OUTPUT_FIELDS = [
    "id",
    "book_id",
    "isbn13",
    "title",
    "author",
    "description",
    "country_code",
    "language_code",
    "image_url",
    "has_image",
    "num_pages",
    "reviews_count",
    "ratings_count",
    "positive_ratings_count",
    "text_reviews_count",
    "average_rating",
    "liked_percent",
    "publication_day",
    "publication_month",
    "publication_year",
    "goodreads_url",
    "etext_number",
    "epub3",
    "epub_older",
    "epub_no_images",
    "genres",
    "has_chapters",
    "has_chunks",
    "num_chapters",
    "num_chunks",
    "summary",
    "has_generic_summary"
]

def books_schema(client: MilvusClient):
    """
    Full schema for the books collection.
    Fields found in this collection:

    Scalar fields                 - Metadata used for filtering, display, and faceting.
    description_embedding         - Embedding of book's description.
    description_embedding_sparse  - Sparse embedding of book's description.
    cover_embedding               - Embedding of a book cover.
    has_image                     - False when an image was unavailable during ingestion, True if it was avaiable.
    summary_embedding             - Embedding od book's LLM summary.
    summary_embedding_sparse      - Sparse embedding of book's LLM summary.
    """
    schema = client.create_schema(
        auto_id=True,
        enable_dynamic_fields=False,
        description=(
            "Books collection with multimodal retrieval support. "
            "Uses the following vectors: "
            " - Dense vectors for descriptions and summaries"
            " - Dense vectors for cover images"
            " - Sparse vectors for descriptions and summaries"
            "Supports multiple different searches."
        ),
    )

    # Scalar metadata
    schema.add_field("id", DataType.INT64, is_primary=True, description="Primary key for books, automatically generated by Milvus")
    schema.add_field("book_id", DataType.VARCHAR, max_length=64, description="Stripped numerical ID for a book from the GoodReads dataset")
    schema.add_field("isbn13", DataType.VARCHAR, max_length=32, description="Book's ISBN from the GoodReads dataset")
    schema.add_field("title", DataType.VARCHAR, max_length=512, description="Title of the book from the created dataset")
    schema.add_field("author", DataType.VARCHAR, max_length=256, description="Book's main author name from the created dataset")
    schema.add_field("country_code", DataType.VARCHAR, max_length=32, description="Book's country code from the created dataset")
    schema.add_field("language_code", DataType.VARCHAR, max_length=32, description="Book's language code from the created dataset")
    schema.add_field("image_url", DataType.VARCHAR, max_length=2048, description="Book's cover image URL from the GoodReads dataset")
    schema.add_field("has_image", DataType.BOOL, description="True when cover_embedding encodes an actual book's cover image, otherwise False")
    schema.add_field("num_pages", DataType.INT32, description="Number of pages for a book from the GoodReads dataset")
    schema.add_field("reviews_count", DataType.INT32, description="Book's number of reviews calculated from the GoodReads dataset")
    schema.add_field("ratings_count", DataType.INT32, description="Book's number of ratings calculated from the GoodReads dataset")
    schema.add_field("positive_ratings_count", DataType.INT32, description="Book's number of positive ratings calculated from the GoodReads dataset")
    schema.add_field("text_reviews_count", DataType.INT32, description="Book's number of text reviews calculated from the GoodReads dataset")
    schema.add_field("average_rating", DataType.FLOAT, description="Book's average rating calculated from the GoodReads dataset and corresponding reviews")
    schema.add_field("liked_percent", DataType.FLOAT, description="Book's liked percent ratio calculated from the GoodReads dataset and corresponding rating values")
    schema.add_field("publication_day", DataType.INT16, description="Book's publication day from the GoodReads dataset")
    schema.add_field("publication_month", DataType.INT16, description="Book's publication month from the GoodReads dataset")
    schema.add_field("publication_year", DataType.INT16, description="Book's publication year from the GoodReads dataset")
    schema.add_field("goodreads_url", DataType.VARCHAR, max_length=2048, description="Book's URL from the GoodReads dataset")
    schema.add_field("etext_number", DataType.VARCHAR, max_length=128, description="Book's etext number from the Project Gutenberg dataset")
    schema.add_field("epub3", DataType.VARCHAR, max_length=2048, description="Book's EPUB3 URL from the Project Gutenberg dataset")
    schema.add_field("epub_older", DataType.VARCHAR, max_length=2048, description="Book's EPUB for older devices URL from the Project Gutenberg dataset")
    schema.add_field("epub_no_images", DataType.VARCHAR, max_length=2048, description="Book's EPUB with no images URL from the Project Gutenberg dataset")
    schema.add_field(field_name="genres", datatype=DataType.ARRAY, element_type=DataType.VARCHAR, max_length=32, max_capacity=16, description="Book's genres from the created dataset")
    schema.add_field("has_chapters", DataType.BOOL, description="True when a book has chapters, otherwise False")
    schema.add_field("has_chunks", DataType.BOOL, description="True when a book has chunks, otherwise False")
    schema.add_field("has_generic_summary", DataType.BOOL, description="True when a book has GoodReads description instead of LLM summary, otherwise false")
    schema.add_field("num_chapters", DataType.INT32, description="Number of chapters found in text of a book")
    schema.add_field("num_chunks", DataType.INT32, description="Number of chunks found in text of a book")

    # --- Text Fields with Full-Text Search (Analyzer) Enabled ---
    schema.add_field(
        "description", 
        DataType.VARCHAR, 
        max_length=8192, 
        enable_analyzer=True,
        analyzer_params={"type": BM25_ANALYZER_LANGUAGE},
        enable_match=True,
        description="Book's description from the GoodReads dataset - text used to build the description_embedding and description_embedding_sparse"
    )
    schema.add_field(
        "summary", 
        DataType.VARCHAR, 
        max_length=8192, 
        enable_analyzer=True,
        analyzer_params={"type": BM25_ANALYZER_LANGUAGE},
        enable_match=True,
        description="Book's summary created by LLM - text used to build the summary_embedding and summary_embedding_sparse"
    )

    # --- Vector fields ---
    # Dense vectors
    schema.add_field("description_embedding", DataType.FLOAT_VECTOR, dim=BOOKS_DESCRIPTION_EMBEDDING_DIM, description="Dense text encoding from book's description")
    schema.add_field("summary_embedding", DataType.FLOAT_VECTOR, dim=BOOKS_SUMMARY_EMBEDDING_DIM, description="Dense text encoding from book's LLM generated summary")

    # Sparse vectors (BM25)
    schema.add_field("description_embedding_sparse", DataType.SPARSE_FLOAT_VECTOR, is_function_output=True, description="Sparse text encoding from book's description")
    schema.add_field("summary_embedding_sparse", DataType.SPARSE_FLOAT_VECTOR, is_function_output=True, description="Sparse text encoding from book's LLM generated summary")

    # Image vector
    schema.add_field("cover_embedding", DataType.FLOAT_VECTOR, dim=BOOKS_COVER_EMBEDDING_DIM, description="Image encoding from book's cover image")

    # BM25 sparse vector auto-populations, used for automatically converting descriptions and summaries into sparse vectors during ingestion
    schema.add_function(Function(name="bm25_books_description", function_type=FunctionType.BM25, input_field_names=["description"], output_field_names=["description_embedding_sparse"]))
    schema.add_function(Function(name="bm25_books_summary", function_type=FunctionType.BM25, input_field_names=["summary"], output_field_names=["summary_embedding_sparse"]))

    return schema


def books_index_params(client: MilvusClient):
    """
    Index parameters for the books collection.

    Scalar indexes — INVERTED for efficient WHERE filtering.
    Vector indexes — IVF_FLAT with COSINE; one index per vector field.
    Sparse vector indexes — SPARSE_INVERTED_INDEX with BM25; one index per vector field.
    """
    idx = client.prepare_index_params()

    # Scalar indexes
    idx.add_index("book_id", index_type="INVERTED")
    idx.add_index("isbn13", index_type="INVERTED")
    idx.add_index("title", index_type="INVERTED")
    idx.add_index("author", index_type="INVERTED")
    idx.add_index("country_code", index_type="INVERTED")
    idx.add_index("language_code", index_type="INVERTED")
    idx.add_index("has_image", index_type="INVERTED")
    idx.add_index("num_pages", index_type="INVERTED")
    idx.add_index("reviews_count", index_type="INVERTED")
    idx.add_index("ratings_count", index_type="INVERTED")
    idx.add_index("positive_ratings_count", index_type="INVERTED")
    idx.add_index("text_reviews_count", index_type="INVERTED")
    idx.add_index("average_rating", index_type="INVERTED")
    idx.add_index("liked_percent", index_type="INVERTED")
    idx.add_index("etext_number", index_type="INVERTED")
    idx.add_index("publication_day", index_type="INVERTED")
    idx.add_index("publication_month", index_type="INVERTED")
    idx.add_index("publication_year", index_type="INVERTED")
    idx.add_index("has_chapters", index_type="INVERTED")
    idx.add_index("has_chunks", index_type="INVERTED")
    idx.add_index("num_chapters", index_type="INVERTED")
    idx.add_index("num_chunks", index_type="INVERTED")
    idx.add_index("has_generic_summary", index_type="INVERTED")

    # --- Dense vector indexes (required) --- 
    # description_embedding 
    idx.add_index(
        field_name="description_embedding",
        index_type="IVF_FLAT",
        index_name="description_embedding_index",
        metric_type="COSINE",
        params={"nlist": BOOKS_NLIST},
    )

    # cover_embedding 
    idx.add_index(
        field_name="cover_embedding",
        index_type="IVF_FLAT",
        index_name="cover_embedding_index",
        metric_type="COSINE",
        params={"nlist": BOOKS_NLIST},
    )

    # description_embedding 
    idx.add_index(
        field_name="summary_embedding",
        index_type="IVF_FLAT",
        index_name="summary_embedding_index",
        metric_type="COSINE",
        params={"nlist": BOOKS_NLIST},
    )

    # --- Sparse vector indexes for traditional keyword/BM25 retrieval (required) ---
    # description_embedding_sparse
    idx.add_index(
        field_name="description_embedding_sparse",
        index_type="SPARSE_INVERTED_INDEX",
        index_name="description_embedding_sparse_index",
        metric_type="BM25",
    )

    # description_embedding_sparse
    idx.add_index(
        field_name="summary_embedding_sparse",
        index_type="SPARSE_INVERTED_INDEX",
        index_name="summary_embedding_sparse_index",
        metric_type="BM25",
    )

    return idx