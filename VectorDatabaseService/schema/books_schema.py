def books_schema(client: MilvusClient):
    """
    Full schema for the books collection.

    Scalar fields                 - Metadata used for filtering, display, and faceting.
    description_embedding         - Embedding od book's description.
    description_embedding_sparse  - Sparse embedding of book's description.
    cover_embedding               - Embedding of a book cover.
    has_image                     - False when an image was unavailable during ingestion, True if it was avaiable.
    summary_embedding             - Embedding od book's LLM summary.
    summary_embedding_sparse      - Sparse embedding of book's LLM summary.
    """
    schema = client.create_schema(
        auto_id=True,
        enable_dynamic_fields=False,
        # description should be investigated later!!!
        description=(
            "Books collection with multimodal retrieval support. "
            "Uses the following vectors: "
            " - MiniLM dense vectors for descriptions (CLIP ViT-B/32, 512-dim, COSINE),"
            " - CLIP dense vectors for covers (CLIP ViT-B/32, 512-dim, COSINE)."
            "Supports: text-semantic, image-similarity, text-to-image, and image-to-text searches."
        ),
    )

    # Scalar metadata
    schema.add_field("id", DataType.INT64, is_primary=True, description="Primary key for books, automatically generated by Milvus")
    schema.add_field("book_id", DataType.VARCHAR, max_length=64, description="Stripped numerical ID for a book from the GoodReads dataset")
    schema.add_field("isbn13", DataType.VARCHAR, max_length=32, description="Book's ISBN from the GoodReads dataset")
    schema.add_field("title", DataType.VARCHAR, max_length=512, description="Title of the book from the created dataset")
    schema.add_field("author", DataType.VARCHAR, max_length=256, description="Book's main author name from the created dataset")
    schema.add_field("description", DataType.VARCHAR, max_length=8192, description="Book's description from the GoodReads dataset - text used to build the description_embedding and description_embedding_sparse")
    schema.add_field("country_code", DataType.VARCHAR, max_length=32, description="Book's country code from the created dataset")
    schema.add_field("language_code", DataType.VARCHAR, max_length=32, description="Book's language code from the created dataset")
    schema.add_field("image_url", DataType.VARCHAR, max_length=2048, description="Book's cover image URL from the GoodReads dataset")
    schema.add_field("has_image", DataType.BOOL, description="True when cover_embedding encodes an actual book's cover image, otherwise false")
    schema.add_field("num_pages", DataType.INT32, is_primary=True, description="Primary key for books, automatically generated by Milvus")
    schema.add_field("reviews_count", DataType.INT32, description="Book's number of reviews calculated from the GoodReads dataset")
    schema.add_field("ratings_count", DataType.INT32, description="Book's number of ratings calculated from the GoodReads dataset")
    schema.add_field("positive_ratings_count", DataType.INT32, description="Book's number of positive ratings calculated from the GoodReads dataset")
    schema.add_field("text_reviews_count", DataType.INT32, description="Book's number of text reviews calculated from the GoodReads dataset")
    schema.add_field("average_rating", DataType.FLOAT, description="Book's average rating calculated from the GoodReads dataset and corresponding reviews")
    schema.add_field("liked_percent", DataType.FLOAT, description="Book's liked percent ratio calculated from the GoodReads dataset and corresponding rating values")

    # ZA PROVERITI!!!
    schema.add_field("publication_day", DataType.INT16, description="Book's publication day from the GoodReads dataset")
    schema.add_field("publication_month", DataType.INT16, description="Book's publication month from the GoodReads dataset")
    schema.add_field("publication_year", DataType.INT16, description="Book's publication year from the GoodReads dataset")

    schema.add_field("goodreads_url", DataType.VARCHAR, max_length=2048, description="Book's URL from the GoodReads dataset")
    schema.add_field("etext_number", DataType.VARCHAR, max_length=128, description="Book's etext number from the Project Gutenberg dataset")
    schema.add_field("epub3", DataType.VARCHAR, max_length=2048, description="Book's EPUB3 URL from the Project Gutenberg dataset")
    schema.add_field("epub_older", DataType.VARCHAR, max_length=2048, description="Book's EPUB for older devices URL from the Project Gutenberg dataset")
    schema.add_field("epub_no_images", DataType.VARCHAR, max_length=2048, description="Book's EPUB with no images URL from the Project Gutenberg dataset")
    schema.add_field(field_name="genres", datatype=DataType.ARRAY, element_type=DataType.VARCHAR, max_length=32, max_capacity=16,  description="Book's genres from the created dataset")

    schema.add_field("has_chapters", DataType.BOOL, description="True when a book has chapters, otherwise false")
    schema.add_field("has_chunks", DataType.BOOL, description="True when a book has chunks, otherwise false")
    schema.add_field("has_generic_summary", DataType.BOOL, description="True when a book has GoodReads description instead of LLM summary, otherwise false")

    schema.add_field("description", DataType.VARCHAR, max_length=8192, description="Book's summary created by LLM - text used to build the summary_embedding and summary_embedding_sparse")

    schema.add_field("num_chapters", DataType.INT32, description="Number of chapters found in text of a book")
    schema.add_field("num_chunks", DataType.INT32, description="Number of chunks found in text of a book")

    # Vector fields
    schema.add_field(
        "description_embedding",
        DataType.FLOAT_VECTOR,
        dim=BOOKS_DESCRIPTION_EMBEDDING_DIM,
        description="CLIP text encoding from description (512-dim)"
    )
    schema.add_field(
        "cover_embedding",
        DataType.FLOAT_VECTOR,
        dim=BOOKS_COVER_EMBEDDING_DIM,
        description="CLIP image encoding from book's cover image (512-dim)"
    )
    return schema