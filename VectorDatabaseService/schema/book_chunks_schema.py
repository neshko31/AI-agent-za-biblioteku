"""
Milvus collection schema for book_chunks collection.
"""

from pymilvus import DataType, Function, FunctionType, MilvusClient

from config import BM25_ANALYZER_LANGUAGE, BOOK_CHUNKS_EMBEDDING_DIM, BOOK_CHUNKS_NLIST

BOOK_CHUNKS_OUTPUT_FIELDS = [
    "id",
    "book_id",
    "title",
    "author",
    "chapter_id",
    "chunk_text",
    "start_pos",
    "end_pos",
    "chunk_label_index",
    "chunk_index"
]


def book_chunks_schema(client: MilvusClient):
    """
    Full schema for the book_chunks collection.
    Fields found in this collection:

    Scalar fields                         - Metadata used for filtering, display, and faceting.
    chapter_summary_embedding             - Embedding of the book chunk text.
    chapter_summary_embedding_sparse      - Sparse embedding of the book chunk text.
    """
    schema = client.create_schema(
        auto_id=True,
        enable_dynamic_fields=False,
        description=(
            "Chapter summaries collection with hybrid retrieval support."
            "Uses the following vectors: "
            " - Dense vectors for chapter_summary"
            " - Sparse vectors for chapter_summary"
            "Supports multiple different searches."
        ),
    )

    # Scalar metadata
    schema.add_field("id", DataType.INT64, is_primary=True, description="Primary key for chapter summaries, automatically generated by Milvus")
    schema.add_field("book_id", DataType.VARCHAR, max_length=32, description="Book's stripped numerical ID from the GoodReads dataset")
    schema.add_field("title", DataType.VARCHAR, max_length=512, description="Title of the book from the created dataset")
    schema.add_field("author", DataType.VARCHAR, max_length=256, description="Book's main author name from the created dataset")
    schema.add_field("chapter_id", DataType.INT64, description="Milvus generated key for chapter_summaries collection, used for matching chunks with chapters")
    schema.add_field("start_pos", DataType.INT64, description="Chapter's starting position in the book from the created dataset")
    schema.add_field("end_pos", DataType.INT64, description="Chapter's ending position in the book from the created dataset")
    schema.add_field("chunk_label_index", DataType.INT32, description="Chunk's index in the chapter of a book from the created dataset")
    schema.add_field("chunk_index", DataType.INT32, description="Chunk's index in a book from the created dataset")
    
    # --- Text Field with Full-Text Search (Analyzer) Enabled ---
    schema.add_field(
        "chunk_text", 
        DataType.VARCHAR, 
        max_length=8192, 
        enable_analyzer=True,
        analyzer_params={"type": BM25_ANALYZER_LANGUAGE},
        enable_match=True,
        description="Chunk's text created with semantic chunking - text used to build the chunk_embedding and chunk_embedding_sparse"
    )
    
    # --- Vector fields ---
    # Dense vector
    schema.add_field("chunk_embedding", DataType.FLOAT_VECTOR, dim=BOOK_CHUNKS_EMBEDDING_DIM, description="Dense text encoding from chunk's text")
    
    # Sparse vector (BM25)
    schema.add_field("chunk_embedding_sparse", DataType.SPARSE_FLOAT_VECTOR, is_function_output=True, description="Sparse text encoding from chunk's text")
    
    # BM25 sparse vector auto-population, it automatically converts review_text into sparse vectors during ingestion
    schema.add_function(Function(name="bm25_book_chunks", function_type=FunctionType.BM25, input_field_names=["chunk_text"], output_field_names=["chunk_embedding_sparse"]))
    
    return schema


def book_chunks_index_params(client: MilvusClient):
    """
    Index parameters for the chapter summaries collection.

    Scalar indexes        — INVERTED for efficient WHERE filtering.
    Dense vector indexes  — IVF_FLAT with COSINE; one index per vector field.
    Sparse vector indexes — SPARSE_INVERTED_INDEX with BM25; one index per vector field.
    """
    idx = client.prepare_index_params()

    # Scalar indexes
    idx.add_index("book_id", index_type="INVERTED")
    idx.add_index("title", index_type="INVERTED")
    idx.add_index("author", index_type="INVERTED")
    idx.add_index("chapter_id", index_type="INVERTED")
    idx.add_index("start_pos", index_type="INVERTED")
    idx.add_index("end_pos", index_type="INVERTED")
    idx.add_index("chunk_label_index", index_type="INVERTED")
    idx.add_index("chunk_index", index_type="INVERTED")

    # --- Dense vector index (required) ---
    # chunk_embedding
    idx.add_index(
        "chunk_embedding",
        index_type="IVF_FLAT",
        index_name="chunk_embedding_index",
        metric_type="COSINE",
        params={"nlist": BOOK_CHUNKS_NLIST},
    )

    # --- Sparse vector index for traditional keyword/BM25 retrieval (required) ---
    # chunk_embedding_sparse
    idx.add_index(
        "chunk_embedding_sparse",
        index_type="SPARSE_INVERTED_INDEX",
        index_name="chunk_embedding_sparse_index",
        metric_type="BM25",
    )

    return idx