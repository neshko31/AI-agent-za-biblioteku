"""
Milvus collection schema for chapter_summaries collection.
"""

from pymilvus import DataType, Function, FunctionType, MilvusClient

from config import BM25_ANALYZER_LANGUAGE, CHAPTER_SUMMARIES_EMBEDDING_DIM, CHAPTER_SUMMARIES_NLIST

CHAPTER_SUMMARIES_OUTPUT_FIELDS = [
    "id",
    "book_id",
    "title",
    "author",
    "chapter_label",
    "chapter_summary",
    "start_pos",
    "end_pos",
    "chapter_index"
]


def chapter_summaries_schema(client: MilvusClient):
    """
    Full schema for the chapter_summaries collection.
    Fields found in this collection:

    Scalar fields                         - Metadata used for filtering, display, and faceting.
    chapter_summary_embedding             - Embedding of the chapter summary.
    chapter_summary_embedding_sparse      - Sparse embedding of the chapter summary.
    """
    schema = client.create_schema(
        auto_id=True,
        enable_dynamic_fields=False,
        description=(
            "Chapter summaries collection with hybrid retrieval support."
            "Uses the following vectors: "
            " - Dense vectors for chapter_summary"
            " - Sparse vectors for chapter_summary"
            "Supports multiple different searches."
        ),
    )

    # Scalar metadata
    schema.add_field("id", DataType.INT64, is_primary=True, description="Primary key for chapter summaries, automatically generated by Milvus")
    schema.add_field("book_id", DataType.VARCHAR, max_length=32, description="Book's stripped numerical ID from the GoodReads dataset")
    schema.add_field("title", DataType.VARCHAR, max_length=512, description="Title of the book from the created dataset")
    schema.add_field("author", DataType.VARCHAR, max_length=256, description="Book's main author name from the created dataset")
    schema.add_field("chapter_label", DataType.VARCHAR, max_length=512, description="Label of the chapter in the book from the created dataset")
    schema.add_field("start_pos", DataType.INT64, description="Chapter's starting position in the book from the created dataset")
    schema.add_field("end_pos", DataType.INT64, description="Chapter's ending position in the book from the created dataset")
    schema.add_field("chapter_index", DataType.INT32, description="Chapter's index in the book from the created dataset")
    
    # --- Text Field with Full-Text Search (Analyzer) Enabled ---
    schema.add_field(
        "chapter_summary", 
        DataType.VARCHAR, 
        max_length=8192, 
        enable_analyzer=True,
        analyzer_params={"type": BM25_ANALYZER_LANGUAGE},
        enable_match=True,
        description="Chapter's summary created by LLM - text used to build the chapter_summary_embedding and chapter_summary_embedding_sparse"
    )
    
    # --- Vector fields ---
    # Dense vector
    schema.add_field("chapter_summary_embedding", DataType.FLOAT_VECTOR, dim=CHAPTER_SUMMARIES_EMBEDDING_DIM, description="Dense text encoding from chapter summary's text")
    
    # Sparse vector (BM25)
    schema.add_field("chapter_summary_embedding_sparse", DataType.SPARSE_FLOAT_VECTOR, is_function_output=True, description="Sparse text encoding from chapter summary's text")
    
    # BM25 sparse vector auto-population, it automatically converts review_text into sparse vectors during ingestion
    schema.add_function(Function(name="bm25_chapter_summaries", function_type=FunctionType.BM25, input_field_names=["chapter_summary"], output_field_names=["chapter_summary_embedding_sparse"]))
    
    return schema


def chapter_summaries_index_params(client: MilvusClient):
    """
    Index parameters for the chapter summaries collection.

    Scalar indexes        — INVERTED for efficient WHERE filtering.
    Dense vector indexes  — IVF_FLAT with COSINE; one index per vector field.
    Sparse vector indexes — SPARSE_INVERTED_INDEX with BM25; one index per vector field.
    """
    idx = client.prepare_index_params()

    # Scalar indexes
    idx.add_index("book_id", index_type="INVERTED")
    idx.add_index("title", index_type="INVERTED")
    idx.add_index("author", index_type="INVERTED")
    idx.add_index("chapter_label", index_type="INVERTED")
    idx.add_index("start_pos", index_type="INVERTED")
    idx.add_index("end_pos", index_type="INVERTED")
    idx.add_index("chapter_index", index_type="INVERTED")

    # --- Dense vector index (required) ---
    # chapter_summary_embedding
    idx.add_index(
        "chapter_summary_embedding",
        index_type="IVF_FLAT",
        index_name="chapter_summary_embedding_index",
        metric_type="COSINE",
        params={"nlist": CHAPTER_SUMMARIES_NLIST},
    )

    # --- Sparse vector index for traditional keyword/BM25 retrieval (required) ---
    # chapter_summary_embedding_sparse
    idx.add_index(
        "chapter_summary_embedding_sparse",
        index_type="SPARSE_INVERTED_INDEX",
        index_name="chapter_summary_embedding_sparse_index",
        metric_type="BM25",
    )

    return idx